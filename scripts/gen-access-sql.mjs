// Writes supabase/migrations/0002_access.sql from src/lib/access.js so the database and the app agree.
// Run: node scripts/gen-access-sql.mjs   (then apply the file to the database)
import { writeFileSync } from 'fs';
import { ACCESS, COLLECTIONS } from '../src/lib/access.js';

const rows = [];
for (const [role, cols] of Object.entries(ACCESS))
  for (const col of COLLECTIONS) {
    const [rd, wr] = cols[col] || ['none', 'none'];
    if (rd !== 'none' || wr !== 'none') rows.push(`  ('${role}', '${col}', '${rd}', '${wr}')`);
  }
const sql = `-- GENERATED by scripts/gen-access-sql.mjs from src/lib/access.js — do not edit by hand.
begin;
delete from skuuulline.access;
insert into skuuulline.access (role, col, rd, wr) values
${rows.join(',\n')};
commit;
`;
writeFileSync(new URL('../supabase/migrations/0002_access.sql', import.meta.url), sql);
console.log(`${rows.length} access rules written`);
